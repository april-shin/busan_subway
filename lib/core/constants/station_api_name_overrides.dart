/// 실시간 도착정보 API **질의**에 사용할 역명을 반환한다(아웃바운드).
///
/// [arrivalApiStationNameOverrides]에 등록된 표시명이면 API 등록명으로 치환하고,
/// 아니면 표시명을 그대로 반환한다. 이름만으로(노선 정보 없이) 치환하므로, 등록 키는
/// 타 노선 동명이역이 없어야 안전하다(수동 확인 사항 — 위 "갱신 방법" 4-(b) 참조).
