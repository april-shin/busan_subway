  // 5·8호선 공용(동일 환승역) — 단, 5호선분은 API 미제공이라 실제로는 8호선만 조회된다
  //   (위 "조사 이력" 보류 항목 참조).
  '천호': '천호(풍납토성)',
  // 우이신설선 — 가운뎃점(·)+공백없음 → 마침표+공백(축약/치환형)
  '4·19민주묘지': '4.19 민주묘지',
  // 신림선 — 앱은 부역명 병기, API는 본역명만(축약/치환형)
  '관악산(서울대)': '관악산',
  // 경강선 — API는 "대"를 뺀 축약명으로만 응답(축약/치환형). 같은 노선 신둔도예촌은
  //   표시명 그대로 조회되므로 치환 불필요(세종대왕릉과 별개 역, 중복 아님).
  '세종대왕릉': '세종왕릉',
};

/// API 등록명 → 표시명 역치환용 맵. 값이 유일하므로 단순 역맵으로 성립한다
/// (유일성은 `station_api_name_overrides_test.dart`가 강제).
final Map<String, String> _displayNameByApiStationName = {
  for (final e in arrivalApiStationNameOverrides.entries) e.value: e.key,
};

/// 실시간 도착정보 API **질의**에 사용할 역명을 반환한다(아웃바운드).
///
/// [arrivalApiStationNameOverrides]에 등록된 표시명이면 API 등록명으로 치환하고,
/// 아니면 표시명을 그대로 반환한다. 이름만으로(노선 정보 없이) 치환하므로, 등록 키는
/// 타 노선 동명이역이 없어야 안전하다(수동 확인 사항 — 위 "갱신 방법" 4-(b) 참조).
String resolveArrivalApiStationName(String displayName) =>
    arrivalApiStationNameOverrides[displayName] ?? displayName;

/// 한 역의 API 등록명이 **노선별로 갈린 역**의 등록명 전체 목록.
///
/// 도착정보 API 는 역명 하나로만 조회되는데, 아래 역들은 같은 물리 역인데도 노선에 따라
/// 서로 다른 이름으로 등록돼 있어 **한 번 조회로는 일부 노선이 통째로 누락된다.**
/// `SeoulApiDataSource` 가 이 목록의 이름으로 각각 조회한 뒤 결과를 병합한다.
///
/// - 질의들은 **대등하다** — 우선순위가 없고, 하나라도 성공하면 합쳐서 보여준다.
///   다만 **첫 원소는 [resolveArrivalApiStationName] 결과와 일치해야 한다**(테스트 강제).
///   이 맵과 위 치환 맵이 따로 놀지 않게 묶어 두는 드리프트 가드다.
/// - 목록의 모든 이름은 인바운드([resolveDisplayStationName])로 표시명에 되돌아와야 한다.
///   위 치환 맵에 등록된 이름은 역맵으로, 표시명과 같은 이름은 항등으로 성립한다(테스트 강제).
/// - **구조적 제약:** 인바운드 역맵이 위 치환 맵에서만 생성되므로, 목록에서 표시명과 다른
///   이름은 **반드시 치환 맵의 값**이어야 한다. 즉 "표시명과 다른 이름이 둘 이상"인 분리
///   역은 현 구조로 표현할 수 없다(치환 맵이 역명당 값 하나이므로). 그런 역이 나오면
///   왕복 테스트가 실패하니 조용한 드리프트는 아니고, 그때 구조를 확장하면 된다.
/// - **비용:** 등록한 역은 새로고침마다 API 를 목록 수만큼 호출한다(서울 열린데이터 일일
///   한도 1,000건/일). 실제로 노선이 갈린 역만 등록할 것.
///
/// 2026-07-31 일괄 조회(`.../ALL`, 3,176행) × `stations.json` 전수 대조로 확정한 2건이
/// 전부다. 조사 스크립트 요지: 역명별 `statnNm→subwayId` 집합을 만들고, 각 표시명의
/// 질의 결과에서 빠진 노선이 **이름이 유사한 다른 등록명** 아래 있는지 검사.
const Map<String, List<String>> arrivalApiSplitRegistrationNames = {
  // 1·4·경의중앙·공항철도 = "서울" (실측 20건) / GTX-A = "서울역" (3건).
  '서울역': ['서울', '서울역'],
  // 5호선 = "올림픽공원(한국체대)" (부역명 병기) / 9호선 = "올림픽공원" (본역명).
  //   실측 각 4건. 순서는 위 치환 맵 항목과 맞춘 것일 뿐 우선순위 의미는 없다.
  '올림픽공원': ['올림픽공원(한국체대)', '올림픽공원'],
};

/// 도착정보 API 질의에 사용할 등록명 **전체**를 반환한다(아웃바운드).
///
/// 등록명이 노선별로 갈린 역([arrivalApiSplitRegistrationNames])이면 목록 전체를,
/// 아니면 [resolveArrivalApiStationName] 결과 한 개짜리 목록을 돌려준다.
/// 첫 원소는 항상 주 질의명이다.
List<String> resolveArrivalApiStationNames(String displayName) =>
    arrivalApiSplitRegistrationNames[displayName] ??
    <String>[resolveArrivalApiStationName(displayName)];

/// API **응답**의 역명(`arvlMsg3` 등)을 앱 표시용 역명으로 되돌린다(인바운드).
///
/// API 등록명이면 표시명으로 치환하고, 아니면 입력을 그대로 반환한다.
/// 부역명을 **덧붙인** 형태는 `_stripStationAlias`로도 복원되지만, 축약·치환형
/// ("지제"→"평택지제")은 이 함수가 유일한 복원 수단이다.
String resolveDisplayStationName(String apiStationName) =>
    _displayNameByApiStationName[apiStationName] ?? apiStationName;

/// 아웃바운드 질의명은 아니지만 API 응답 **텍스트**에 부가 표기로 섞여 오는 문자열 →
/// 표시명. (양방향 치환맵과 분리 — 이 값들은 조회용 정식명이 아니므로 왕복 불변식·
/// 값 유일성 대상이 아니다.) 예: 응암순환 종착 열차의 위치 표기 "응암(하선-종착)".
const Map<String, String> _inboundOnlyTextReplacements = {
  '응암(하선-종착)': '응암',
};

/// 자유텍스트 치환([resolveDisplayInText])을 **경계가 맞을 때만** 수행할 API 등록명과,
/// 그 이름이 실제로 그 역을 가리킬 때 **뒤따르는 문맥**(정규식 조각).
///
/// 여기 있는 이름은 **다른 역 표시명의 부분 문자열**이라 무조건 치환하면 엉뚱한 역명을
/// 만들어낸다. 그렇다고 통째로 빼면 방면 라벨·도착 메시지에 API 표기가 그대로 남는다.
/// 두 문맥이 서로소임을 실측으로 확인한 경우, 뒤따르는 문자로 구분해 안전하게 치환한다.
const Map<String, String> _boundedTextReplacementSuffixes = {
  // '서울' ⊂ 서울대입구 · 서울숲 · 서울대벤처타운 · 서울지방병무청 · 관악산(서울대).
  //   무조건 치환하면 "서울대입구방면" → "서울역대입구방면" 으로 오염된다.
  //
  //   2026-08-01 실측 — 두 문맥이 서로소다:
  //     API 가 역 "서울"을 가리킬 때 뒤: 공백("서울 진입")·문자열 끝(statnNm·bstatnNm·
  //       arvlMsg3)·"행"("서울행")·"방면"("서울방면")
  //     다른 역 이름에서 "서울" 뒤: 대 · 숲 · 지 · 역
  //   `stations.json` 653개 역명 중 "서울" 뒤에 공백이 오는 이름은 없다.
  '서울': r'[ 행]|방면|$',
};

/// [_boundedTextReplacementSuffixes]를 "이름 + 뒤따르는 문맥" 전방탐색 패턴으로 컴파일.
final Map<String, RegExp> _boundedTextPatterns = {
  for (final e in _boundedTextReplacementSuffixes.entries)
    e.key: RegExp('${RegExp.escape(e.key)}(?=${e.value})'),
};

/// 자유텍스트 치환 **후보** API 표기 전체 — 양방향 맵 값 + 인바운드 전용.
///
/// 테스트가 "다른 역 표시명의 부분 문자열인 후보가 경계 규칙 없이 무조건 치환되고
/// 있지 않은지"를 전수 검사하려면 두 소스를 모두 봐야 하므로 공개한다.
@visibleForTesting
final List<String> textReplacementCandidates = <String>[
  ..._displayNameByApiStationName.keys,
  ..._inboundOnlyTextReplacements.keys,
];

/// 무조건 치환할 API 표기를 긴 것부터 정렬 — 부분 문자열 겹침 방지.
/// 경계 규칙이 붙은 이름([_boundedTextReplacementSuffixes])은 여기서 빼고 따로 처리한다.
final List<String> _apiNamesByLengthDesc = textReplacementCandidates
    .where((n) => !_boundedTextReplacementSuffixes.containsKey(n))
    .toList()
  ..sort((a, b) => b.length.compareTo(a.length));

/// 자유텍스트 치환용 통합 역맵(API 표기 → 표시명). 경계 규칙이 붙은 이름도 치환 대상이라
/// (경계가 맞을 때) 여기 남겨 둔다.
final Map<String, String> _textReplacements = {
  ..._displayNameByApiStationName,
  ..._inboundOnlyTextReplacements,
};

/// 자유 텍스트(방면 라벨 `trainLineNm`·도착 메시지 `arvlMsg2` 등)에 **부분 문자열로**
/// 섞여 오는 API 등록명을 표시용 역명으로 되돌린다(인바운드, 표시 전용).
///
/// 예: "응암순환(상선)행 - 응암순환(상선)방면" → "응암행 - 응암방면",
///     "4분 후 (증산(명지대앞))" → "4분 후 (증산)".
/// [resolveDisplayStationName]은 문자열 전체가 역명일 때만 동작하므로, 역명이
/// 다른 텍스트에 끼어 오는 경우를 위해 별도 제공한다. 다른 역명의 부분 문자열인
/// API명(예: "서울" ⊂ "서울대입구")은 [_boundedTextReplacementSuffixes]의 경계 규칙에
/// 맞을 때만 치환해 오염을 막는다 — "서울 진입"→"서울역 진입"은 바꾸고
/// "서울대입구방면"은 그대로 둔다.
/// 시간·역수 파싱
/// (`parseTimeFromMessage`/`parseStationCount`)은 역명을 사용하지 않으므로 이
/// 정규화는 파싱 결과에 영향을 주지 않는다(표시 문자열만 정리).
String resolveDisplayInText(String text) {
  if (text.isEmpty) return text;
  var out = text;

  // 경계 조건부 치환을 먼저 — 경계 문맥은 **원본 API 텍스트** 기준으로 실측했으므로,
  // 다른 치환이 만들어낸 문자열 위에서 판정하지 않는다.
  _boundedTextPatterns.forEach((apiName, pattern) {
    if (out.contains(apiName)) {
      out = out.replaceAll(pattern, _textReplacements[apiName]!);
    }
  });

  for (final apiName in _apiNamesByLengthDesc) {
    if (out.contains(apiName)) {
      out = out.replaceAll(apiName, _textReplacements[apiName]!);
    }
  }
  return out;
}
