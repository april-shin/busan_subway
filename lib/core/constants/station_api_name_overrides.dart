///   "지제") 작업이라 규칙으로 유도할 수 없어 실측 기반 하드코딩 맵이 유일 수단이다.
/// - **인바운드(응답명)**: [resolveDisplayStationName] — API 등록명 → 표시명(위 맵의 역).
///   응답의 `arvlMsg3`(현재역)가 API 등록명으로 오는데, 이를 표시명으로 되돌려야
///   `stations.json` 매칭(라이브맵 좌표 조회·도착시간 추정)이 성립한다.
///   * 부역명을 **덧붙인** 형태("오목교(목동운동장앞)")는 `live_train_provider`의
