/// 서울 열린데이터 실시간 도착정보 API(`realtimeStationArrival`) 역명 치환 맵.
///
/// 일부 역은 API가 **부역명(병기역명)이 포함되거나 개명 전인 정식 등록명**으로만
/// 조회된다. 앱 내부 표시용 역명(`stations.json`)은 간결한/현행 이름을 쓰므로,
/// 표시명 그대로 질의하면 API가 `{"status":500,"code":"INFO-200",
/// "message":"해당하는 데이터가 없습니다."}` 를 반환해 도착정보가 통째로 비어 버린다.
///
/// 예) 앱 "남한산성입구" → API는 "남한산성입구(성남법원,검찰청)" 에만 응답.
///
/// 이 맵은 **API 질의명(아웃바운드)** 을 치환하기 위한 것이다. 앱 내부 상태·그래프·
/// 환승 계산·캐시 키·화면 표시는 계속 표시용 역명을 사용한다.
///
/// ## 방향성
/// - **아웃바운드(질의명)**: [resolveArrivalApiStationName] — 표시명 → API 등록명.
///   부역명을 덧붙이거나("오목교"→"오목교(목동운동장앞)") 축약/치환하는("평택지제"→
///   "지제") 작업이라 규칙으로 유도할 수 없어 실측 기반 하드코딩 맵이 유일 수단이다.
/// - **인바운드(응답명)**: [resolveDisplayStationName] — API 등록명 → 표시명(위 맵의 역).
///   응답의 `arvlMsg3`(현재역)가 API 등록명으로 오는데, 이를 표시명으로 되돌려야
///   `stations.json` 매칭(라이브맵 좌표 조회·도착시간 추정)이 성립한다.
///   * 부역명을 **덧붙인** 형태("오목교(목동운동장앞)")는 `live_train_provider`의
///     `_stripStationAlias` 괄호 제거 규칙으로도 복원되지만,
///   * **축약·치환** 형태("지제"→"평택지제", "관악산"→"관악산(서울대)")는 규칙으로
///     복원 불가하므로 이 역맵이 유일한 복원 수단이다. (그래서 인바운드도 맵이 필요.)
///
/// ## 갱신 방법
/// "○○역 도착정보가 안 보인다" 제보가 오면:
///   1. 표시명 그대로 API 호출 → `INFO-200`(데이터 없음)인지 확인.
///   2. 부역명/구역명을 붙인 정식명으로 재호출 → 도착정보가 나오면 아래 맵에
///      `'표시명': 'API등록명'` 추가.
///   3. 정식명을 모르면 `realtimePosition`(노선별 열차 위치) API의 `statnNm`에서 확인.
///   4. **추가 전 확인(필수):** (a) 표시명이 `stations.json`에 실존하는지, (b) 같은
///      이름의 **타 노선 별개 역**(동명이역)이 없는지, (c) API 등록명(값)이 다른 역의
///      표시명과 충돌하지 않는지, (d) API 등록명(값)이 **다른 역 표시명의 부분 문자열**은
///      아닌지 — 맞다면 [resolveDisplayInText]가 자유텍스트를 오염시키므로
///      ("서울" ⊂ "서울대입구") [_textReplacementExclusions]에도 등록할 것.
///      → (a)·(c)·(d) 및 값 유일성·이중치환 방지는 `station_api_name_overrides_test.dart`가
///      자동 검증한다(추가 후 테스트가 깨지면 위반 의심). **(b) 동명이역 부재는 자동
///      검증하지 않으므로 수동 확인이 필수** — 이름 기반(노선 무관) 치환이라 동명이역이
///      있으면 엉뚱한 역 도착정보를 보일 수 있다.
///   5. 한 역의 등록명이 **노선별로 다를 수 있다**(예: 서울역 — 1·4·경의중앙·공항철도는
///      "서울", GTX-A는 "서울역"). 이 맵은 역명당 하나만 고를 수 있으므로 열차 수가 많은
///      쪽을 택하고, 빠지는 노선을 조사 이력에 남긴다.
///
/// ## 조사 이력 / 미해결
/// 최초 조사: 2026-07-25. 도착정보 API가 실제 제공하는 전 노선을 전수 스윕해 확인.
